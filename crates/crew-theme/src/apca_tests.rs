use super::*;

/// The reference pairs published with APCA-W3 0.0.98G.
#[test]
fn matches_the_published_reference_pairs() {
    let near = |got: f32, want: f32| (got - want).abs() < 0.2;
    assert!(
        near(lc((0x88, 0x88, 0x88), (0xff, 0xff, 0xff)), 63.1),
        "{}",
        lc((0x88, 0x88, 0x88), (0xff, 0xff, 0xff))
    );
    assert!(near(lc((0xff, 0xff, 0xff), (0x88, 0x88, 0x88)), 68.5));
    assert!(near(lc((0x00, 0x00, 0x00), (0xaa, 0xaa, 0xaa)), 58.1));
    assert!(near(lc((0x11, 0x22, 0x33), (0xdd, 0xee, 0xff)), 91.7));
}

#[test]
fn a_colour_on_itself_has_no_contrast() {
    assert_eq!(lc((0x40, 0x80, 0xc0), (0x40, 0x80, 0xc0)), 0.0);
}
